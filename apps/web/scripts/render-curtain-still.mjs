/**
 * Renders the entrance curtain's closed pose (components/layout/curtain-cloth.tsx, time 0, pointer
 * at rest) into public/curtain/closed-landscape.webp and closed-portrait.webp with headless Chrome,
 * so the very first paint already shows the real curtain and the live cloth takes over invisibly.
 * Re-run after changing the shader:  CHROME_PATH=... node scripts/render-curtain-still.mjs
 * (needs puppeteer-core on the module path).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'components/layout/curtain-cloth.tsx'), 'utf8');
const fragment = /const FRAGMENT = \/\* glsl \*\/ `([\s\S]*?)`;/.exec(source)?.[1];
if (!fragment) throw new Error('FRAGMENT shader not found in curtain-cloth.tsx');

/** [name, CSS width, CSS height, device scale]: a laptop and a phone at the scales the live cloth draws at (CLOTH_SCALE). */
const scales = /CLOTH_SCALE = \{ desktop: ([\d.]+), phone: ([\d.]+) \}/.exec(source);
if (!scales) throw new Error('CLOTH_SCALE not found in curtain-cloth.tsx');
const SIZES = [
  ['closed-landscape', 1440, 900, Number(scales[1])],
  ['closed-portrait', 430, 932, Number(scales[2])],
];
/** Width of the tiny inline placeholder (shown until the still has downloaded). */
const TINY = 48;
const executablePath = process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await puppeteer.launch({ executablePath, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setContent('<!doctype html><canvas id="c"></canvas>');
mkdirSync(join(root, 'public/curtain'), { recursive: true });
const tiny = {};
for (const [name, w, h, scale] of SIZES) {
  const [dataUrl, tinyUrl] = await page.evaluate(
    // Runs inside the page
    /* global document */
    ([frag, cw, ch, sc, tinyW]) => {
      const c = document.getElementById('c');
      c.width = cw * sc;
      c.height = ch * sc;
      const gl = c.getContext('webgl', { premultipliedAlpha: false, antialias: false, preserveDrawingBuffer: true });
      const prog = gl.createProgram();
      for (const [type, src] of [
        [gl.VERTEX_SHADER, 'attribute vec2 p;void main(){gl_Position=vec4(p,0.,1.);}'],
        [gl.FRAGMENT_SHADER, frag],
      ]) {
        const sh = gl.createShader(type);
        gl.shaderSource(sh, src);
        gl.compileShader(sh);
        if (!gl.getShaderParameter(sh, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(sh));
        gl.attachShader(prog, sh);
      }
      gl.linkProgram(prog);
      gl.useProgram(prog);
      const buf = gl.createBuffer();
      gl.bindBuffer(gl.ARRAY_BUFFER, buf);
      gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 1, -1, -1, 1, 1, 1]), gl.STATIC_DRAW);
      const loc = gl.getAttribLocation(prog, 'p');
      gl.enableVertexAttribArray(loc);
      gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
      const u = (n) => gl.getUniformLocation(prog, n);
      gl.viewport(0, 0, c.width, c.height);
      gl.uniform2f(u('u_res'), c.width, c.height);
      gl.uniform1f(u('u_time'), 0);
      gl.uniform1f(u('u_open'), 0);
      gl.uniform1f(u('u_tug'), 0);
      gl.uniform1f(u('u_fade'), 0);
      gl.uniform2f(u('u_pointer'), 0.5, 0.5);
      gl.uniform3f(u('u_ripple'), 0.5, 0.5, -10);
      gl.uniform1f(u('u_scale'), sc);
      gl.uniform1f(u('u_still'), 1);
      gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
      // The tiny placeholder: the same picture at a few dozen pixels, as a data URI
      const t = document.createElement('canvas');
      t.width = tinyW;
      t.height = Math.round((tinyW * ch) / cw);
      t.getContext('2d').drawImage(c, 0, 0, t.width, t.height);
      return [c.toDataURL('image/webp', 0.86), t.toDataURL('image/webp', 0.6)];
    },
    [fragment, w, h, scale, TINY],
  );
  const file = join(root, 'public/curtain', `${name}.webp`);
  writeFileSync(file, Buffer.from(dataUrl.split(',')[1], 'base64'));
  tiny[name] = tinyUrl;
  console.log(name, `${w}×${h}@${scale}`, `${Math.round(readFileSync(file).length / 1024)} KB`, `tiny ${tinyUrl.length} B`);
}
// The placeholders go into a stylesheet as custom properties (app/curtain-tiny.css, imported by globals.css).
writeFileSync(
  join(root, 'app/curtain-tiny.css'),
  `/* Generated by scripts/render-curtain-still.mjs: the entrance curtain at a few dozen pixels, shown until the still downloads. */\n:root {\n  --curtain-tiny-landscape: url('${tiny['closed-landscape']}');\n  --curtain-tiny-portrait: url('${tiny['closed-portrait']}');\n}\n`,
);
await browser.close();
